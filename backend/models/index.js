const { Schema } = mongoose
const objectId = Schema.Types.ObjectId
const safeJson = {
  toJSON: {
    virtuals: true,
    transform(_doc, value) {
      if (value?._id) value.id = value._id.toString()
      delete value._id
      delete value.__v
      delete value.passwordHash
      return value
    },
  },
}
const make = (name, definition, options = {}) => {
  const { indexes = [], ...schemaOptions } = options
  const schema = new Schema(definition, { timestamps: true, ...safeJson, ...schemaOptions })
  for (const index of indexes) schema.index(index.fields, index.options)
  return mongoose.models[name] || mongoose.model(name, schema)
}
